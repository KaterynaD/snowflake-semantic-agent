-- Access role
CREATE ROLE IF NOT EXISTS CHATGPT_MCP_READER;

GRANT DATABASE ROLE SNOWFLAKE.CORTEX_AGENT_USER
    TO ROLE CHATGPT_MCP_READER;

-- Warehouse
GRANT USAGE ON WAREHOUSE SNOWFLAKE_LEARNING_DB
    TO ROLE CHATGPT_MCP_READER;

-- Database and schemas
GRANT USAGE ON DATABASE DW
    TO ROLE CHATGPT_MCP_READER;

GRANT USAGE ON SCHEMA DW.SERVICE
    TO ROLE CHATGPT_MCP_READER;

GRANT USAGE ON SCHEMA DW.COMMON
    TO ROLE CHATGPT_MCP_READER;

GRANT USAGE ON SCHEMA DW.REVENUE
    TO ROLE CHATGPT_MCP_READER;

GRANT USAGE ON SCHEMA DW.USAGE
    TO ROLE CHATGPT_MCP_READER;

-- MCP server
GRANT USAGE ON MCP SERVER DW.SERVICE.BUSINESS_MCP
    TO ROLE CHATGPT_MCP_READER;

-- Existing Cortex Agent
GRANT USAGE ON AGENT DW.SERVICE.BUSINESS_MCP
    TO ROLE CHATGPT_MCP_READER;

-- Semantic views
GRANT REFERENCES, SELECT
    ON SEMANTIC VIEW DW.REVENUE.BOOKING
    TO ROLE CHATGPT_MCP_READER;

GRANT REFERENCES, SELECT
    ON SEMANTIC VIEW DW.REVENUE.ARR
    TO ROLE CHATGPT_MCP_READER;

GRANT REFERENCES, SELECT
    ON SEMANTIC VIEW DW.USAGE.PRODUCT_USAGE
    TO ROLE CHATGPT_MCP_READER;

-- Account knowledge procedure
GRANT USAGE ON PROCEDURE
    DW.SERVICE.ACCOUNT_QUERY(VARCHAR, VARCHAR, VARCHAR)
    TO ROLE CHATGPT_MCP_READER;

--MCP Server
GRANT USAGE ON AGENT DW.SERVICE.BUSINESS_ANALYTICS_AGENT
    TO ROLE CHATGPT_MCP_READER;

GRANT DATABASE ROLE SNOWFLAKE.CORTEX_ANALYST_USER
    TO ROLE CHATGPT_MCP_READER;

CREATE USER IF NOT EXISTS CHATGPT_MCP_USER
    TYPE = PERSON
    LOGIN_NAME = 'CHATGPT_MCP_USER'
    PASSWORD = 'XYZ'
    MUST_CHANGE_PASSWORD = TRUE
    DEFAULT_ROLE = CHATGPT_MCP_READER
    DEFAULT_SECONDARY_ROLES = ()
    COMMENT = 'Read-only ChatGPT MCP connection';

ALTER USER CHATGPT_MCP_USER
    SET DEFAULT_WAREHOUSE = 'SNOWFLAKE_LEARNING_WH';

-- Assign role to your existing Snowflake user
GRANT ROLE CHATGPT_MCP_READER
    TO USER CHATGPT_MCP_USER;

SHOW GRANTS TO USER CHATGPT_MCP_USER;

SHOW GRANTS TO ROLE CHATGPT_MCP_READER;


