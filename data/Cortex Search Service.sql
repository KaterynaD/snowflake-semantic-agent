
-- Individual account names
CREATE OR REPLACE CORTEX SEARCH SERVICE
    DW.SERVICE.ACCOUNT_NAME_SEARCH
    ON NAME
    WAREHOUSE = SNOWFLAKE_LEARNING_WH
    TARGET_LAG = '1 day'
AS
SELECT DISTINCT NAME
FROM DW.COMMON.DIM_ACCOUNT
WHERE NAME IS NOT NULL
  AND TRIM(NAME) <> '';

-- District names
CREATE OR REPLACE CORTEX SEARCH SERVICE
    DW.SERVICE.DISTRICT_NAME_SEARCH
    ON DISTRICT_NAME
    WAREHOUSE = SNOWFLAKE_LEARNING_WH
    TARGET_LAG = '1 day'
AS
SELECT DISTINCT DISTRICT_NAME
FROM DW.COMMON.DIM_ACCOUNT
WHERE DISTRICT_NAME IS NOT NULL
  AND TRIM(DISTRICT_NAME) <> '';

-- Customer names
CREATE OR REPLACE CORTEX SEARCH SERVICE
    DW.SERVICE.CUSTOMER_NAME_SEARCH
    ON CUSTOMER_NAME
    WAREHOUSE = SNOWFLAKE_LEARNING_WH
    TARGET_LAG = '1 day'
AS
SELECT DISTINCT CUSTOMER_NAME
FROM DW.COMMON.DIM_ACCOUNT
WHERE CUSTOMER_NAME IS NOT NULL
  AND TRIM(CUSTOMER_NAME) <> '';


